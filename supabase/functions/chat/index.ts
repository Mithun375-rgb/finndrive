import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

const SYSTEM_PROMPT = `You are Findrive AI, an intelligent financial assistant specialized in helping users with:

1. **Money Management & Budgeting**: Creating budgets, tracking expenses, the 50/30/20 rule, and financial planning.
2. **Investments**: Stocks, mutual funds, ETFs, SIPs, risk management, and building wealth.
3. **Scholarships & Education Funding**: Finding scholarships, education loans, and financial aid.
4. **Startups & Entrepreneurship**: Business planning, funding, pitching, and scaling ventures.
5. **Savings Tips**: Emergency funds, compound interest, and smart saving strategies.
6. **Basic Math**: You can solve mathematical expressions when asked (e.g., interest calculations, budget math, percentages).

Guidelines:
- Be friendly, clear, and educational in your responses
- Provide actionable advice with examples when helpful
- For math problems, show your work step-by-step
- Keep responses concise but comprehensive
- If asked about topics outside finance/math, politely redirect to your areas of expertise
- Use Indian Rupee (₹) for currency examples unless user specifies otherwise
- Always encourage users to verify financial decisions with certified professionals

Remember: You're helping young people become financially literate and confident!`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    
    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(
          JSON.stringify({ error: "Rate limit exceeded. Please try again in a moment." }),
          { status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" } }
        );
      }
      if (response.status === 402) {
        return new Response(
          JSON.stringify({ error: "Service temporarily unavailable. Please try again later." }),
          { status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" } }
        );
      }
      const errorText = await response.text();
      console.error("AI gateway error:", response.status, errorText);
      return new Response(
        JSON.stringify({ error: "Failed to get AI response" }),
        { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
      );
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("Chat error:", e);
    return new Response(
      JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }),
      { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  }
});
